/// The real club at [rank] (0 = strongest) in division [d] (0-based):
/// (name, town).
(String, String) realClub(LeagueCountry country, int d, int rank) {
  final parts = _clubs[country]![d][rank].split('|');
  return (parts[0], parts[1]);
}

/// Every club in a country, for checks.
Iterable<String> realClubNames(LeagueCountry country) => [
  for (final division in _clubs[country]!)
    for (final c in division) c.split('|').first,
];

