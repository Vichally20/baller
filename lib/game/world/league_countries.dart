/// Where a person is from, with name pools for generating fictional people.
enum Nationality {
  english('English', _englishFirst, _englishLast),
  spanish('Spanish', _spanishFirst, _spanishLast),
  german('German', _germanFirst, _germanLast),
  french('French', _frenchFirst, _frenchLast),
  italian('Italian', _italianFirst, _italianLast),
  brazilian('Brazilian', _brazilianFirst, _brazilianLast),
  argentine('Argentine', _argentineFirst, _argentineLast),
  japanese('Japanese', _japaneseFirst, _japaneseLast),
  nigerian('Nigerian', _nigerianFirst, _nigerianLast),
  ghanaian('Ghanaian', _ghanaianFirst, _ghanaianLast);

  const Nationality(this.label, this.firstNames, this.lastNames);

  final String label;
  final List<String> firstNames;
  final List<String> lastNames;

  String randomName(Random rng) =>
      '${firstNames[rng.nextInt(firstNames.length)]} '
      '${lastNames[rng.nextInt(lastNames.length)]}';
}

